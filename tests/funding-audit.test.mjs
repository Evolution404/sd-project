 await api('/agreements/'+a.id,'DELETE',{version:a.version,preview_token:emptyPreview.token,reason:'预览后出现新关联'},409);
 assert.equal(one('SELECT status FROM agreements WHERE id=?',a.id).status,'active');
 db.prepare("UPDATE projects SET status='approved',approved_budget_fen=40000 WHERE id=?").run(p.id);
