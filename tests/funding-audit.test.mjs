 await api('/dictionary-deletion/voltage/'+builtin.id,'DELETE',{version:builtin.version});
 const deletion=one("SELECT id FROM audit_events WHERE entity='voltage_levels' AND entity_id=? AND action='delete'",builtin.id);
 await api('/audit-records/'+deletion.id,'DELETE',{version:0,reason:'隐藏不清理原始删除决定'});
 execFileSync(process.execPath,['--input-type=module','-e',"await import('./server/server.mjs');"],{env:{...process.env,DATA_DIR:root,SD_DISABLE_LISTEN:'1'}});
 assert.ok(!(await api('/voltage-levels')).some(x=>x.id===builtin.id));
 assert.ok((await api('/dictionary-workspace')).deleted_items.some(x=>x.id===builtin.id));
 const protectedFrame=await frame('审计隐藏不恢复框架');await agreement('保留授权协议',protectedFrame);
 await api('/frameworks/'+protectedFrame.id,'DELETE',{version:protectedFrame.version,reason:'逻辑删除框架'});
 const frameworkDeletion=one("SELECT id FROM audit_events WHERE entity='frameworks' AND entity_id=? AND action='delete'",protectedFrame.id);
