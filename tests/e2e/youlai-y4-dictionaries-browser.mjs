import assert from "node:assert/strict";
import {mkdirSync,existsSync} from "node:fs";
import {join,resolve} from "node:path";
import {chromium} from "playwright";
import {fixture} from "../helpers.mjs";
import {httpServer} from "../../dist/server/platform/http/server.js";

const dispose=[];
const {s,user,save}=fixture({after:fn=>dispose.push(fn)});
const srv=httpServer(s,{staticDirectory:resolve(process.env.SD_BROWSER_STATIC_DIRECTORY || "dist/web")});
await new Promise(ok=>srv.listen(0,"127.0.0.1",ok));
const port=srv.address().port;
const root=process.cwd();
const out=join(root,"test-results","youlai-y4");
mkdirSync(out,{recursive:true});
let browser,page;
try{
  browser=await chromium.launch(existsSync(chromium.executablePath())?
    {headless:true}:{headless:true,channel:"chrome"});
  page=await browser.newPage({viewport:{ width: 1920, height: 1080 }});
  const errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  const base=`http://127.0.0.1:${port}/`;
  await page.goto(base+"#/login");
  await page.getByPlaceholder("用户名").fill("admin");
  await page.getByPlaceholder("密码").fill("Schema113-test-password");
  await page.getByRole("button",{name:"登录",exact:true}).click();
  await page.waitForURL(url=>url.hash.startsWith("#/dashboard"),{timeout:18000});
  await page.goto(base+"#/configuration/dictionaries");
  await page.getByRole("button",{name:"新增计量单位"}).waitFor({timeout:15000});
  await page.getByRole("button",{name:"新增计量单位"}).click();
  let dialog=page.getByRole("dialog").last();
  await dialog.getByRole("textbox",{name:"计量单位名称"}).fill("计量精度验收米");
  await dialog.getByRole("spinbutton",{name:"允许小数位数"}).fill("3");
  await dialog.getByRole("button",{name:"确定"}).click();
  await page.getByText("计量精度验收米",{exact:true}).first().waitFor({timeout:14000});
  const unit=s.catalog.list("units").find(x=>x.name==="计量精度验收米");
  assert.ok(unit);
  assert.equal(unit.quantity_precision,3);
  assert.equal(unit.version,1);
  await page.screenshot({path:join(out,"dictionary-unit-1920.png"),fullPage:true});
  const row=page.getByRole("row").filter({hasText:"计量精度验收米"}).first();
  await row.getByRole("button",{name:"修订"}).click();
  dialog=page.getByRole("dialog").last();
  await dialog.locator(".el-input-number__decrease").click();
  assert.equal(await dialog.getByRole("spinbutton",{name:"允许小数位数"}).inputValue(),"2");
  await dialog.getByRole("button",{name:"确定"}).click();
  await page.getByText("最多 2 位小数",{exact:true}).first().waitFor({timeout:15000});
  const adopted=s.catalog.get("units",unit.id);
  assert.equal(adopted.version,2);
  assert.equal(adopted.quantity_precision,2);
  await row.getByRole("button",{name:"更多操作"}).click();
  await page.getByRole("menuitem",{name:"历史"}).click();
  await page.getByText("V1",{exact:true}).first().waitFor({timeout:12000});
  await page.getByText("V2",{exact:true}).first().waitFor({timeout:12000});
  await page.screenshot({path:join(out,"dictionary-unit-history-1920.png"),fullPage:true});
  await page.locator(".el-drawer:visible .el-drawer__close-btn").click();

  await page.getByRole("tab",{name:"杆塔性质"}).click();
  for (const name of ["耐张", "直线"]) await page.getByRole("cell",{name,exact:true}).waitFor();
  await page.getByRole("button",{name:"新增杆塔性质"}).click();
  dialog=page.getByRole("dialog").last();
  await dialog.getByRole("textbox",{name:"杆塔性质名称"}).fill("专用测试悬垂");
  await dialog.getByRole("button",{name:"确定"}).click();
  await page.getByText("专用测试悬垂",{exact:true}).first().waitFor({timeout:15000});
  assert.ok(s.catalog.list("tower_natures").some(x=>x.name==="专用测试悬垂"));
  await page.getByRole("tab",{name:"杆塔材质"}).click();
  for (const name of ["角钢塔", "钢管杆"]) await page.getByRole("cell",{name,exact:true}).waitFor();
  await page.getByRole("button",{name:"新增杆塔材质"}).click();
  dialog=page.getByRole("dialog").last();
  await dialog.getByRole("textbox",{name:"杆塔材质名称"}).fill("专用测试钢管塔");
  await dialog.getByRole("button",{name:"确定"}).click();
  await page.getByText("专用测试钢管塔",{exact:true}).first().waitFor({timeout:15000});
  const material=s.catalog.list("tower_materials").find(x=>x.name==="专用测试钢管塔");
  assert.ok(material?.id && material.status === "active");
  await page.screenshot({path:join(out,"dictionary-tower-material-1920.png"),fullPage:true});
  await page.goto(base+"#/assets/ledger");
  await page.getByRole("tab",{name:"物理杆塔",exact:true}).click();
  await page.getByRole("columnheader",{name:"杆塔材质",exact:true}).waitFor();
  assert.equal(await page.getByRole("columnheader",{name:/塔型/}).count(),0);
  await page.getByRole("button",{name:"新增物理杆塔",exact:true}).click();
  const physicalForm=page.getByRole("dialog",{name:"新增物理杆塔",exact:true});
  for (const [field, name] of [["杆塔性质", "耐张"], ["杆塔材质", material.name]]) {
    await physicalForm.getByRole("combobox",{name:field,exact:true}).click();
    await page.getByRole("option",{name,exact:true}).click();
  }
  await physicalForm.getByRole("button",{name:"确定",exact:true}).click();
  await physicalForm.waitFor({state:"hidden"});
  const physical=s.catalog.list("physical").find(row=>row.tower_material===material.id);
  assert.ok(physical);
  assert.equal(physical.tower_nature,"tension");
  await page.getByRole("row").filter({has:page.getByRole("cell",{name:material.name,exact:true})})
    .getByRole("cell",{name:"耐张",exact:true}).waitFor();
  await page.goto(base+"#/configuration/dictionaries");
  await page.getByRole("tab",{name:"杆塔材质",exact:true}).click();
  await page.getByRole("row").filter({has:page.getByRole("cell",{name:material.name,exact:true})})
    .getByRole("button",{name:"修订",exact:true}).click();
  const reviseMaterial=page.getByRole("dialog").last();
  await reviseMaterial.getByRole("textbox",{name:"杆塔材质名称"}).fill("专用钢管塔复核版");
  await reviseMaterial.getByRole("button",{name:"确定",exact:true}).click();
  await reviseMaterial.waitFor({state:"hidden"});
  assert.equal(s.catalog.get("tower_materials",material.id).version,2);
  await page.goto(base+"#/assets/ledger");
  await page.getByRole("tab",{name:"物理杆塔",exact:true}).click();
  await page.getByRole("cell",{name:"专用钢管塔复核版",exact:true}).waitFor();
  assert.equal(s.catalog.get("physical",physical.id).tower_material,material.id);
  await page.goto(base+"#/configuration/dictionaries");
  await page.getByRole("tab",{name:"组织目录",exact:true}).click();
  for (const name of ["运检部门甲","运检部门乙"]) {
    await page.getByRole("button",{name:"新增组织",exact:true}).click();
    const organizationForm=page.getByRole("dialog",{name:"新增组织"});
    await organizationForm.getByRole("textbox",{name:"组织名称"}).fill(name);
    await organizationForm.getByRole("button",{name:"确定"}).click();
    await organizationForm.waitFor({state:"hidden"});
    await page.getByRole("heading",{name,exact:true}).waitFor();
  }
  await page.getByRole("treeitem",{name:"运检部门甲",exact:true}).click();
  await page.getByRole("button",{name:"新增下级",exact:true}).click();
  const childForm=page.getByRole("dialog",{name:"新增组织"});
  await childForm.getByText("运检部门甲",{exact:true}).waitFor();
  await childForm.getByRole("textbox",{name:"组织名称"}).fill("运检班组");
  await childForm.getByRole("button",{name:"确定"}).click();
  await childForm.waitFor({state:"hidden"});
  await page.getByRole("heading",{name:"运检班组",exact:true}).waitFor();
  const nodes=s.organizations.tree(user);
  const parentA=nodes.find(row=>row.name==="运检部门甲");
  const parentB=nodes.find(row=>row.name==="运检部门乙");
  const child=nodes.find(row=>row.name==="运检班组");
  assert.equal(child.parent_id,parentA.id);
  const framework=save("frameworks",{name:"组织归口验收框架",fiscal_year:2026,limit_fen:100000});
  const project=s.projects.save(user,{name:"历史归口项目",framework_id:framework.id,managing_unit_id:child.id});
  await page.getByRole("button",{name:"调整上级"}).click();
  const move=page.getByRole("dialog",{name:"调整组织上级"});
  await move.locator(".el-select").click();
  await page.getByRole("option",{name:"运检部门乙",exact:true}).click();
  assert.equal(await move.getByRole("button",{name:"确认迁移"}).isDisabled(),true);
  await move.getByRole("button",{name:"核对迁移影响"}).click();
  await move.getByText("运检部门甲 / 运检班组",{exact:true}).waitFor();
  await move.getByText("运检部门乙 / 运检班组",{exact:true}).waitFor();
  await move.getByRole("button",{name:"确认迁移"}).click();
  await move.waitFor({state:"hidden"});
  await page.getByRole("row").filter({hasText:"运检部门乙 / 运检班组"}).waitFor();
  await page.getByRole("row").filter({hasText:"运检部门甲 / 运检班组"}).waitFor();
  assert.equal(s.organizations.tree(user).find(row=>row.id===child.id).parent_id,parentB.id);
  assert.equal(s.projects.get(project.id).managing_unit_version_id,child.unit_version_id);
  await page.getByRole("tab",{name:"项目采用",exact:true}).click();
  const adoptedProject=page.getByRole("row").filter({hasText:"历史归口项目"});
  await adoptedProject.getByRole("cell",{name:"1",exact:true}).waitFor();
  await page.screenshot({path:join(out,"organization-history-adoption-1920.png")});
  await page.getByRole("treeitem",{name:"运检部门甲",exact:true}).click();
  await page.getByRole("button",{name:"删除组织"}).click();
  await page.getByRole("dialog",{name:"核对组织删除影响"}).getByRole("button",{name:"确认删除"}).click();
  await page.getByRole("treeitem",{name:"运检部门甲",exact:true}).waitFor({state:"hidden"});
  await page.getByText("显示已删除",{exact:true}).click();
  await page.getByRole("treeitem",{name:/运检部门甲.*已删除/}).waitFor();
  assert.equal(s.organizations.tree(user).find(row=>row.id===parentA.id).deleted,true);
  assert.ok(s.organizations.detail(user,parentA.id).versions.length);
  assert.deepEqual(errors,[]);
  console.log("YOULAI_Y4_DICTIONARIES_OK fixed precision, dictionary history, tower nature and material, organization move and frozen project adoption");
}catch(error){
  await page?.screenshot({path:join(out,"dictionary-failure.png"),fullPage:true}).catch(()=>{});
  throw error;
}finally{
  await browser?.close();

  await new Promise(ok=>srv.close(ok));
  for(const clean of dispose.reverse())await clean();
}
