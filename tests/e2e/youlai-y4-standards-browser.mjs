import {pickDemandPositions} from "./youlai-business-worksheet-helpers.mjs";
import assert from "node:assert/strict";
import {fixture} from "../helpers.mjs";
import {httpServer} from "../../dist/server/platform/http/server.js";
import {chromium} from "playwright";
import {resolve} from "node:path";
import { mkdirSync } from "node:fs";
const cleanup=[];
const f=fixture({after:x=>cleanup.push(x)});
const backend=httpServer(f.s,{staticDirectory:resolve(process.env.SD_BROWSER_STATIC_DIRECTORY || "dist/web")});
await new Promise(ok=>backend.listen(0,"127.0.0.1",ok));
const port=backend.address().port;
let browser;
try {
  browser=await chromium.launch({headless:true,channel:"chrome"});
  const page=await browser.newPage({viewport:{ width: 1920, height: 1080 }});
  const errors=[];
  page.on("pageerror",error=>errors.push(error.message));
  const base="http://127.0.0.1:"+port+"/#";
  await page.goto("http://127.0.0.1:"+port+"/#/login");
  await page.getByPlaceholder("用户名").fill("admin");
  await page.getByPlaceholder("密码").fill("Schema113-test-password");
  await page.getByRole("button",{name:"登录",exact:true}).click();
  await page.waitForURL(url=>url.hash.startsWith("#/dashboard"));
  await page.goto("http://127.0.0.1:"+port+"/#/standards/operations");
  await page.getByRole("button",{name:"新增作业对象"}).waitFor({timeout:13000});
  await page.getByRole("button",{name:"新增作业对象"}).click();
  let dialog=page.getByRole("dialog").last();
  await dialog.getByRole("textbox",{name:"名称"}).fill("参考作业对象");
  await dialog.locator(".el-form-item").filter({hasText:"对象位置"}).locator(".el-select").click();
  await page.getByRole("option",{name:"本体"}).last().click();
  await dialog.locator(".el-form-item").filter({hasText:"归属单元"}).locator(".el-select").click();
  await page.getByRole("option",{name:"物理杆塔"}).last().click();
  await dialog.getByRole("button",{name:"确定"}).click();
  await page.getByText("参考作业对象",{exact:true}).first().waitFor({timeout:10000});
  const obj=f.s.catalog.list("objects").find(x=>x.name==="参考作业对象");
  assert.equal(obj.object_position,"body");
  assert.equal(obj.attribution_unit,"physical_tower");
  await page.getByRole("tab",{name:"操作类型"}).click();
  await page.getByRole("button",{name:"新增操作类型"}).click();
  dialog=page.getByRole("dialog").last();
  await dialog.getByRole("textbox",{name:"名称"}).fill("参考作业操作类型");
  await dialog.locator(".el-form-item").filter({hasText:"作业对象"}).locator(".el-select").click();
  await page.getByRole("option",{name:"参考作业对象"}).last().click();
  await dialog.locator(".el-form-item").filter({hasText:"固定计量单位"}).locator(".el-select").click();
  await page.getByRole("option",{name:"套"}).last().click();
  const choose = async (scope,label,option) => {
    const control=scope.locator(".el-form-item").filter({has:page.getByText(label,{exact:true})}).locator(".el-select");
    await control.click();
    const list=await control.getByRole("combobox").getAttribute("aria-controls");
    await page.locator("[id='"+list+"']").getByRole("option",{name:option,exact:true}).click();
  };
  await dialog.getByRole("tab",{name:"录入模板"}).click();
  await dialog.getByRole("textbox",{name:"建议数量"}).fill("2");
  await dialog.getByRole("textbox",{name:"验收标准"}).fill("首版验收需力矩确认");
  await dialog.getByRole("tab",{name:"附加属性"}).click();
  await dialog.getByRole("button",{name:"添加附加属性"}).click();
  const attribute=page.getByRole("dialog",{name:"配置附加属性"});
  await attribute.getByRole("textbox",{name:"属性名称"}).fill("作业系数");
  await choose(attribute,"层级","需求级");
  await choose(attribute,"字段类型","小数");
  await attribute.getByRole("textbox",{name:"最小值"}).fill("1.00");
  await attribute.getByRole("textbox",{name:"最大值"}).fill("3.00");
  await attribute.getByRole("textbox",{name:"默认值"}).fill("1.25");
  await attribute.getByRole("button",{name:"应用属性"}).click();
  await attribute.waitFor({state:"hidden"});
  await dialog.getByRole("button",{name:"保存正式版本"}).click();
  await page.getByText("参考作业操作类型",{exact:true}).first().waitFor({timeout:10000});
  const op=f.s.catalog.list("operations").find(x=>x.name==="参考作业操作类型");
  assert.ok(op);
  assert.equal(op.work_object_id,obj.id);
  assert.equal(op.default_unit_id,f.unit.id);
  assert.equal(op.default_quantity_scaled,20000);
  const [definition]=JSON.parse(op.attributes_schema_json);
  assert.equal(definition.precision,2);
  assert.equal(definition.default_value,"1.25");

  await page.goto(base+"/business/demands/edit");
  await page.getByRole("combobox",{name:"操作类型"}).fill(op.name);
  await page.getByRole("option",{name:op.name,exact:true}).click();
  await page.getByRole("textbox",{name:"问题描述"}).fill("采用第一版作业定义的现场需求");
  const coefficient=page.getByRole("textbox",{name:"作业系数"});
  assert.equal(await coefficient.inputValue(),"1.25");
  await coefficient.fill("1.75");
  await page.getByRole("tab",{name:"作业位置（0）"}).click();
  await pickDemandPositions(page,[["T15",/T15/]]);
  await page.getByRole("button",{name:"保存专业需求"}).click();
  await page.locator(".el-drawer:visible").getByText("作业位置（1）",{exact:true}).waitFor();
  const [demand]=f.s.demands.search({page:1,page_size:20,q:"采用第一版作业定义",filters:{}}).items;
  assert.ok(demand);
  assert.equal(f.s.demands.get(demand.id).operation_version,1);
  assert.equal(f.s.demands.get(demand.id).attributes[definition.key],"1.75");
  assert.equal(f.s.demands.get(demand.id).work_locations[0].quantity_scaled,20000);

  await page.goto(base+"/standards/operations");
  await page.getByRole("tab",{name:"操作类型",exact:true}).click();
  const row=page.getByRole("row").filter({hasText:op.name});
  await row.getByRole("button",{name:"修订",exact:true}).click();
  dialog=page.getByRole("dialog",{name:"修订操作类型"});
  await dialog.getByRole("tab",{name:"录入模板"}).click();
  await dialog.getByRole("textbox",{name:"验收标准"}).fill("第二版验收增加影像留存");
  await dialog.getByRole("tab",{name:"附加属性"}).click();
  await dialog.getByRole("button",{name:"编辑属性"}).click();
  await attribute.getByRole("textbox",{name:"默认值"}).fill("2.25");
  await attribute.getByRole("button",{name:"应用属性"}).click();
  await attribute.waitFor({state:"hidden"});
  await dialog.getByRole("button",{name:"保存正式版本"}).click();
  await dialog.waitFor({state:"hidden"});
  const revised=f.s.standards.getOperation(op.id);
  assert.equal(revised.version,2);
  assert.equal(revised.default_unit_version,op.default_unit_version);
  assert.equal(JSON.parse(revised.attributes_schema_json)[0].key,definition.key);
  assert.equal(JSON.parse(revised.attributes_schema_json)[0].default_value,"2.25");
  assert.equal(f.s.demands.get(demand.id).operation_version,1);
  assert.equal(f.s.demands.get(demand.id).attributes[definition.key],"1.75");
  await row.getByRole("button",{name:"查看",exact:true}).click();
  dialog=page.getByRole("dialog",{name:"查看操作类型"});
  await dialog.getByRole("tab",{name:"正式版本与引用"}).click();
  await dialog.getByText(demand.demand_no,{exact:true}).waitFor();
  await dialog.getByRole("button",{name:"查看第1版定义",exact:true}).click();
  await dialog.getByText("首版验收需力矩确认",{exact:true}).waitFor();
  mkdirSync("test-results/youlai-y4",{recursive:true});
  await page.screenshot({path:"test-results/youlai-y4/standard-frozen-reference-1920.png"});
  assert.deepEqual(errors,[]);
  console.log("YOULAI_Y4_STANDARDS_OK four operation tabs, typed attributes, immutable adoption and actual demand references");
}finally{
 await browser?.close();await new Promise(ok=>backend.close(ok));
 for(const clean of cleanup.reverse())await clean();
}
