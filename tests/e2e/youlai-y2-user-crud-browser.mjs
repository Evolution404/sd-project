import assert from "node:assert/strict";
import {mkdirSync,existsSync} from "node:fs";
import {join,resolve} from "node:path";
import {chromium} from "playwright";
import {fixture} from "../helpers.mjs";
import {httpServer} from "../../dist/server/platform/http/server.js";

const clean=[];
const {s,user:administrator}=fixture({after:fn=>clean.push(fn)});
s.identity.revoke(administrator.id);
const server=httpServer(s,{staticDirectory:resolve(process.env.SD_BROWSER_STATIC_DIRECTORY || "dist/web")});
await new Promise(done=>server.listen(0,"127.0.0.1",done));
const port=server.address().port;
const root=process.cwd();
const out=join(root,"test-results","youlai-y2");
mkdirSync(out,{recursive:true});
let browser,page;
try{
  browser=await chromium.launch(existsSync(chromium.executablePath())?
    {headless:true}:{headless:true,channel:"chrome"});
  page=await browser.newPage({viewport:{ width: 1920, height: 1080 }});
  const errors=[];page.on("pageerror",e=>errors.push(e.message));
  const base=`http://127.0.0.1:${port}/`;
  await page.goto(base+"#/login");
  await page.getByPlaceholder("用户名").fill("admin");
  await page.getByPlaceholder("密码").fill("Schema113-test-password");
  await page.getByRole("button",{name:"登录",exact:true}).click();
  await page.waitForURL(url=>url.hash.startsWith("#/dashboard"),{timeout:14000});
  await page.goto(base+"#/configuration/users");
  await page.getByRole("button",{name:"新增用户"}).waitFor({timeout:16000});
  await page.getByText("admin",{exact:true}).first().waitFor({timeout:12000});
  await page.screenshot({path:join(out,"admin-user-crud-page-1920.png"),fullPage:true});
  await page.getByRole("button",{name:"新增用户"}).click();
  const dialog=page.getByRole("dialog").last();
  await dialog.getByRole("textbox",{name:"登录账号"}).fill("tech-operator");
  await dialog.getByRole("textbox",{name:"姓名"}).fill("线路运检人员");
  await dialog.getByRole("textbox",{name:"工号"}).fill("TEST-1009");
  await dialog.locator('input[type="password"]').fill("User-Crud-Test-2026!");
  await dialog.getByRole("button",{name:"确定"}).click();
  await page.getByText("tech-operator",{exact:true}).first().waitFor({timeout:15000});
  const user=s.identity.users().find(x=>x.username==="tech-operator");
  assert.ok(user,"user must be persisted to database");
  assert.equal(user.display_name,"线路运检人员");
  assert.deepEqual(s.identity.rolesForUser(user.id),["viewer"]);
  const row=page.getByRole("row").filter({hasText:"tech-operator"}).first();
  await row.getByRole("button",{name:"编辑"}).click();
  const edit=page.getByRole("dialog").last();
  await edit.getByRole("textbox",{name:"姓名"}).fill("现场设备主人");
  await edit.getByRole("button",{name:"确定"}).click();
  await page.getByText("现场设备主人",{exact:true}).first().waitFor({timeout:15000});
  assert.equal(s.identity.user(user.id).display_name,"现场设备主人");
  await page.screenshot({path:join(out,"admin-user-crud-edited-1920.png"),fullPage:true});
  const newAccount = await browser.newPage({viewport:{ width: 1920, height: 1080 }});
  newAccount.on("pageerror", e => errors.push(e.message));
  await newAccount.goto(base+"#/business/demands");
  await newAccount.getByPlaceholder("用户名").fill("tech-operator");
  await newAccount.getByPlaceholder("密码").fill("User-Crud-Test-2026!");
  await newAccount.getByRole("button",{name:"登录",exact:true}).click();
  await newAccount.waitForURL(/#\/change-initial-password/);
  assert.equal((await newAccount.request.get(base+"api/demands")).status(),403);
  const pendingCookie = (await newAccount.context().cookies()).find(c => c.name === "sd113");
  assert.ok(pendingCookie?.httpOnly);
  await newAccount.reload();
  await newAccount.getByRole("heading",{name:"更改临时密码"}).waitFor();
  await newAccount.screenshot({path:join(out,"first-password-change-1920.png")});
  await newAccount.getByLabel("临时密码",{exact:true}).fill("User-Crud-Test-2026!");
  await newAccount.getByLabel("新密码",{exact:true}).fill("Activated-Password-Y2!");
  await newAccount.getByLabel("再次输入新密码",{exact:true}).fill("Activated-Password-Y2!");
  await newAccount.getByRole("button",{name:"保存并重新登录"}).click();
  await newAccount.waitForURL(/#\/login/);
  assert.throws(() => s.auth.actor(pendingCookie.value), /请登录/);
  assert.equal(s.identity.mustChangePassword(user.id),false);
  assert.throws(() => s.auth.login("tech-operator","User-Crud-Test-2026!"), /账号或密码错误/);
  await newAccount.getByPlaceholder("用户名").fill("tech-operator");
  await newAccount.getByPlaceholder("密码").fill("Activated-Password-Y2!");
  await newAccount.getByRole("button",{name:"登录",exact:true}).click();
  await newAccount.waitForURL(/#\/business\/demands/);
  assert.equal((await newAccount.request.get(base+"api/demands")).status(),200);
  await newAccount.close();
  const remote=s.auth.login("admin","Schema113-test-password");
  await page.goto(base+"#/profile");
  await page.getByRole("heading",{name:"有效登录会话",exact:true}).waitFor();
  const sessions=page.getByRole("table");
  await sessions.getByRole("row").filter({has:page.getByRole("cell",{name:"有效",exact:true})})
    .getByRole("button",{name:"结束会话"}).click();
  await page.getByRole("dialog",{name:"结束会话"}).getByRole("button",{name:"确定"}).click();
  await sessions.getByRole("cell",{name:"有效",exact:true}).waitFor({state:"hidden"});
  assert.throws(()=>s.auth.actor(remote.token),/请登录/);
  const beforePasswordChange=s.auth.login("admin","Schema113-test-password");
  await page.getByRole("button",{name:"修改密码",exact:true}).click();
  const passwordForm=page.getByRole("dialog",{name:"修改密码"});
  const passwordInputs=passwordForm.locator('input[type="password"]');
  await passwordInputs.nth(0).fill("Schema113-test-password");
  await passwordInputs.nth(1).fill("Rotated-Password-For-Y2-Test");
  await passwordInputs.nth(2).fill("Rotated-Password-For-Y2-Test");
  await passwordForm.getByRole("button",{name:"保存并重新登录"}).click();
  await page.waitForURL(/#\/login/);
  assert.throws(()=>s.auth.actor(beforePasswordChange.token),/请登录/);
  assert.throws(()=>s.auth.login("admin","Schema113-test-password"),/账号或密码错误/);
  await page.getByPlaceholder("用户名").fill("admin");
  await page.getByPlaceholder("密码").fill("Rotated-Password-For-Y2-Test");
  await page.getByRole("button",{name:"登录",exact:true}).click();
  await page.waitForURL(/#\/profile/);
  await page.getByRole("heading",{name:"有效登录会话",exact:true}).waitFor();
  await page.screenshot({path:join(out,"personal-session-management-1920.png"),fullPage:false});
  assert.deepEqual(errors,[]);
  console.log("YOULAI_Y2_USER_CRUD_OK original CrudPage, persisted user changes, own session revocation and password rotation");
}catch(e){
  if(page)await page.screenshot({path:join(out,"user-crud-failure.png"),fullPage:true}).catch(()=>{});
  throw e;
}finally{
  await browser?.close();

  await new Promise(done=>server.close(done));
  for(const fn of clean.reverse())await fn();
}
