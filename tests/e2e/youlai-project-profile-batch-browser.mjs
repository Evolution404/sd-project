import assert from "node:assert/strict";
import { existsSync, mkdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { chromium } from "playwright";
import { fixture } from "../helpers.mjs";
import { httpServer } from "../../dist/server/platform/http/server.js";
import { selectWorksheetCell, worksheetCanvas } from "./youlai-business-worksheet-helpers.mjs";
import { copySettlementSelection, pasteSettlementCells } from "./youlai-settlement-grid-helpers.mjs";
import { alignmentAudit } from "./youlai-alignment-helpers.mjs";

const cleanup = [];
const { s, user, save, demandInput, unit } = fixture({ after: fn => cleanup.push(fn) });
const framework = save("frameworks", { fiscal_year: 2026, name: "子项目工作表专项框架", limit_fen: 1000000 });
const demands = demandInput.work_locations.slice(0, 2).map((location, index) => {
  const demand = s.demands.save(user, {
    ...demandInput, problem_description: "跨需求物资夹具" + index, work_locations: [location],
  });
  return s.demands.transition(user, demand.id, { status: "active", expected_version: 1, expected_event_seq: 1 });
});
const material = s.materials.save(user, { name: "跨需求批准物资夹具", unit_id: unit.id, status: "active" });
const server = httpServer(s, { staticDirectory: resolve(process.env.SD_BROWSER_STATIC_DIRECTORY || "dist/web") });
await new Promise(done => server.listen(0, "127.0.0.1", done));
const origin = "http://127.0.0.1:" + server.address().port;
const out = resolve("test-results/youlai-project-profile-batch");
mkdirSync(out, { recursive: true });
let browser, page;

try {
  browser = await chromium.launch(existsSync(chromium.executablePath()) ? { headless: true } : { headless: true, channel: "chrome" });
  const context = await browser.newContext({ viewport: { width: 1920, height: 1080 }, colorScheme: "dark" });
  await context.grantPermissions(["clipboard-read", "clipboard-write"], { origin });
  page = await context.newPage();
  await page.addInitScript(() => localStorage.setItem("vea:ui:theme","auto"));
  const failures = [];
  page.on("pageerror", error => failures.push(error.message));
  await page.goto(origin + "/#/login");
  await page.getByPlaceholder("用户名").fill("admin");
  await page.getByPlaceholder("密码").fill("Schema113-test-password");
  const button = name => page.getByRole("button", { name, exact: true });
  await button("登录").click();
  await page.waitForURL(/#\/dashboard/);
  await page.goto(origin + "/#/business/projects");
  await button("批量新增子项目").click();
  await button("选择年度框架").click();
  const picker = page.getByRole("dialog", { name: "选择批量新增的年度框架", exact: true });
  await picker.getByRole("row").filter({ hasText: framework.name }).getByRole("button", { name: "选择", exact: true }).click();
  await picker.getByRole("button", { name: "选用年度框架（1）", exact: true }).click();
  await page.getByRole("spinbutton", { name: "新增行数" }).fill("2");
  await button("新增档案行").click();
  const profiles = page.getByRole("region", { name: "子项目档案", exact: true });
  const canvas = await worksheetCanvas(profiles);
  const widths = [146, 250, 145, 145, 155, 250, 180];
  await selectWorksheetCell(canvas, 1, 1, widths);
  await pasteSettlementCells(page, "工作表创建甲\t2026-12-01\t2026-12-12\t12.31\t估算甲\n工作表创建乙\t2026-12-02\t2026-12-13\t17.50\t估算乙");
  await button("预检档案").click();
  await page.getByText("已预检 2 条档案，问题 0 项", { exact: true }).waitFor();
  const query = { page: 1, page_size: 20, q: "工作表创建", filters: {} };
  assert.equal(s.projects.search(query).total, 0);
  await page.waitForFunction(() => document.documentElement.classList.contains("dark"));
  assert.deepEqual((await alignmentAudit(page)).violations, []);
  await page.screenshot({ path: join(out, "profiles-dark.png"), animations: "disabled" });
  await button("整批保存档案").click();
  await button("确认保存").click();
  await page.getByRole("heading", { name: "批量新增子项目", exact: true }).waitFor({ state: "hidden" });
  const recorded = s.projects.search(query).items;
  assert.equal(recorded.length, 2);
  const first = recorded.find(row => row.name === "工作表创建甲");
  assert.equal(s.projects.get(first.id).preliminary_estimate_fen, 1231);
  assert.equal(s.projects.get(first.id).framework_id, framework.id);

  const second = recorded.find(row => row.name === "工作表创建乙");
  await page.getByRole("row").filter({ hasText: second.name }).locator("label.el-checkbox").click();
  await button("批量修订项目档案").click();
  const reviseCanvas = await worksheetCanvas(profiles);
  await selectWorksheetCell(reviseCanvas, 1, 4, widths);
  await pasteSettlementCells(page, "31.07");
  await button("预检档案").click();
  await page.getByText("已预检 1 条档案，问题 0 项", { exact: true }).waitFor();
  await button("整批保存档案").click();
  await button("确认保存").click();
  await page.getByRole("heading", { name: "批量修订子项目档案", exact: true }).waitFor({ state: "hidden" });
  assert.equal(s.projects.get(second.id).preliminary_estimate_fen, 3107);
  assert.equal(s.projects.get(second.id).profile_version, 2);

  let staged = s.projects.get(first.id);
  for (const demand of demands) staged = s.projects.link(user, staged.id, { demand_id: demand.id, expected_version: staged.version });
  staged = s.projects.stock(user, staged.id, { expected_version: staged.version });
  await page.emulateMedia({ colorScheme: "light" });
  await page.waitForFunction(() => !document.documentElement.classList.contains("dark"));
  await page.goto(origin + "/#/business/projects/" + staged.id + "/approval/compile");
  await page.getByRole("textbox", { name: "拟批准预算（元）" }).fill("130.00");
  await button("添加批准物资").click();
  const scopes = page.getByRole("dialog", { name: "选择批准物资归属需求", exact: true });
  for (const demand of demands) await scopes.getByRole("row").filter({ hasText: demand.demand_no }).locator("label.el-checkbox").click();
  await scopes.getByRole("button", { name: "选择归属需求（2）", exact: true }).click();
  const materials = page.getByRole("dialog", { name: "选择批准物资", exact: true });
  await materials.getByRole("row").filter({ hasText: material.name }).locator("label.el-checkbox").click();
  await materials.getByRole("button", { name: "添加所选物资（1）", exact: true }).click();
  const materialRegion = page.getByRole("region", { name: "批准物资数量", exact: true });
  const materialCanvas = await worksheetCanvas(materialRegion);
  const materialWidths = [140, 180, 110, 145, 125];
  await selectWorksheetCell(materialCanvas, 1, 3, materialWidths);
  await pasteSettlementCells(page, "2\n4");
  await selectWorksheetCell(materialCanvas, 2, 2, materialWidths);
  await materialRegion.getByRole("button", { name: "移除选中物资", exact: true }).click();
  await materialRegion.getByText("共 1 行", { exact: true }).waitFor();
  await materialRegion.getByRole("button", { name: "撤销", exact: true }).click();
  await materialRegion.getByText("共 2 行", { exact: true }).waitFor();
  await selectWorksheetCell(materialCanvas, 2, 3, materialWidths);
  assert.equal((await copySettlementSelection(page)).trim(), "4");
  const included = page.getByRole("checkbox", { name: "纳入 " + demands[1].demand_no, exact: true });
  const scopeLabel = page.locator("label.el-checkbox").filter({ has: included });
  await scopeLabel.click();
  await materialRegion.getByText("显示 1 行", { exact: true }).waitFor();
  await scopeLabel.click();
  await materialRegion.getByText("显示 2 行", { exact: true }).waitFor();
  await selectWorksheetCell(materialCanvas, 2, 3, materialWidths);
  assert.equal((await copySettlementSelection(page)).trim(), "4");
  await page.screenshot({ path: join(out, "approved-materials-light.png"), animations: "disabled" });
  await button("保存立项草稿").click();
  await page.waitForURL(/\/approval\/review/);
  const draft = s.projects.get(staged.id).approvals[0];
  assert.equal(draft.scopes.length, 2);
  assert.deepEqual(draft.scopes.flatMap(scope => scope.materials).map(item => item.approved_quantity_scaled).sort(), [20000, 40000]);
  assert.ok(draft.scopes.every(scope => scope.materials[0].material_id === material.id));
  await button("集中核价").click();
  const quote = page.getByRole("dialog", { name: "批准范围参考报价", exact: true });
  await quote.getByText(/完整参考价/).waitFor();
  const selection = quote.getByRole("combobox", { name: "批准需求" });
  await selection.click();
  await page.getByRole("option", { name: draft.scopes[1].demand_no, exact: true }).click();
  await quote.getByText(/完整参考价/).waitFor();
  await quote.getByRole("button", { name: "关闭报价", exact: true }).click();
  assert.deepEqual(failures, []);
  console.log("YOULAI_PROJECT_PROFILE_BATCH_OK batch project facts and cross-demand approved materials");
} catch (error) {
  await page?.screenshot({ path: join(out, "failure.png"), animations: "disabled" }).catch(() => {});
  throw error;
} finally {
  await browser?.close();
  await new Promise(done => server.shutdown(done));
  for (const fn of cleanup.reverse()) await fn();
}
