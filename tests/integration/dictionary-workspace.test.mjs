import test,{before,after} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {execFileSync} from 'node:child_process';
import {once} from 'node:events';
import ExcelJS from 'exceljs';
const root=mkdtempSync(join(tmpdir(),'sd-dictionary-'));
process.env.DATA_DIR=root;process.env.SD_DISABLE_LISTEN='1';
const {db,one,all}=await import('../../server/database/index.mjs');
const {app}=await import('../../server/main.mjs');
let base,cookie;
before(async()=>{
 execFileSync(process.execPath,['scripts/init-admin.mjs'],{env:{...process.env,SD_ADMIN_USER:'dictionary-admin',SD_ADMIN_PASSWORD:'test'}});
 app.listen(0,'127.0.0.1');await once(app,'listening');base='http://127.0.0.1:'+app.address().port;
 const response=await fetch(base+'/api/auth/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({username:'dictionary-admin',password:'test'})});
 assert.equal(response.status,200);cookie=response.headers.get('set-cookie').split(';')[0];
});
after(async()=>{app.close();await once(app,'close');db.close();rmSync(root,{recursive:true,force:true})});
async function api(path,body,expected=200,method=body?'POST':'GET'){
 const response=await fetch(base+'/api'+path,{method,headers:{cookie,'content-type':'application/json'},body:body?JSON.stringify(body):undefined});
 const data=await response.json();assert.equal(response.status,expected,path+': '+JSON.stringify(data));return data;
}
test('dictionary workspace: real defaults and usage counts, name-only creation and atomic status/reorder changes',async()=>{
 let view=await api('/dictionary-workspace');
 assert.equal(view.items.filter(x=>x.type_id==='voltage'&&x.builtin).length,8);
 assert.equal(view.stats.builtin,view.items.filter(x=>x.builtin).length);
 assert.equal(view.stats.referenced,0);
 assert.ok(view.categories.every(x=>!['team','erection'].includes(x.id)));
 const voltage=view.items.find(x=>x.type_id==='voltage'&&x.name==='35kV');
 const line=await api('/lines',{name:'字典引用线路',voltage_level_id:voltage.id},201);
 const unit=await api('/dictionary-items',{type_id:'unit',name:'审核专用单位'},201);
 assert.match(unit.code,/^DICT-[0-9a-f]{32}$/);
 const operation=await api('/dictionary-items',{type_id:'operation',operation_profile:{location_kinds:['tower'],default_location_kind:'tower',default_target_object:'',entry_hint:''},work_target_type:'line',name:'审核专用操作',default_unit_id:unit.id},201);
 view=await api('/dictionary-workspace');
 assert.equal(view.items.find(x=>x.id===voltage.id).usage_count,1);
 assert.equal(view.items.find(x=>x.id===unit.id).usage_count,0);
 assert.equal(view.items.find(x=>x.id===unit.id).configuration_usage_count,1);
 assert.equal(view.items.find(x=>x.id===unit.id).builtin,false);
 const originalCode=unit.code;
 const renamed=await api('/dictionary-items/'+unit.id,{name:'修改后的单位',version:unit.version},200,'PATCH');
 assert.equal(renamed.code,originalCode);
 await api('/dictionary-status/unit',{status:'inactive',rows:[{id:unit.id,version:unit.version}]},409);
 assert.equal(one('SELECT status FROM dictionary_items WHERE id=?',unit.id).status,'active');
 const builtinUnit=view.items.find(x=>x.type_id==='unit'&&x.builtin);
 await api('/dictionary-status/unit',{status:'inactive',rows:[{id:builtinUnit.id,version:builtinUnit.version},{id:unit.id,version:unit.version}]},409);
 assert.equal(one('SELECT status FROM dictionary_items WHERE id=?',builtinUnit.id).status,'active','stale last row must roll back all changes');
 await api('/dictionary-status/unit',{status:'inactive',rows:[{id:unit.id,version:renamed.version}]});
 assert.equal(one('SELECT default_unit_id FROM operations WHERE id=?',operation.id).default_unit_id,unit.id,'disable retains reference');
 await api('/dictionary-items/'+operation.id,{version:operation.version,name:'更名操作',default_unit_id:unit.id},200,'PATCH');
 assert.equal(one('SELECT COUNT(*) n FROM dictionary_item_versions WHERE item_id=?',unit.id).n,3);
 await api('/dictionary-status/voltage',{status:'inactive',rows:[{id:voltage.id,version:voltage.version}]});
 assert.equal(one('SELECT voltage_level_id FROM transmission_lines WHERE id=?',line.id).voltage_level_id,voltage.id);
 await api('/lines',{name:'停用电压不可新增线路',voltage_level_id:voltage.id},422);
 view=await api('/dictionary-workspace');
 const order=view.items.filter(x=>x.type_id==='unit').reverse().map(x=>({id:x.id,version:x.version}));
 await api('/dictionary-order/unit',{rows:order});
 const sorted=all("SELECT * FROM dictionary_items WHERE type_id='unit' ORDER BY sort_order");
 assert.deepEqual(sorted.map(x=>x.id),order.map(x=>x.id));
 assert.equal(sorted.find(x=>x.id===unit.id).code,originalCode);
 const before=sorted.map(x=>({id:x.id,version:x.version,sort_order:x.sort_order}));
 await api('/dictionary-order/unit',{rows:order},409);
 assert.deepEqual(all("SELECT id,version,sort_order FROM dictionary_items WHERE type_id='unit' ORDER BY sort_order").map(x=>({...x})),before);
 await api('/dictionary-status/voltage',{status:'inactive',rows:[{id:unit.id,version:3}]},422);
});
test('dictionary deletion: unused custom entries can be deleted; real, historical and draft references remain protected',async()=>{
 const item=await api('/dictionary-items',{type_id:'unit',name:'可删除单位'},201);
 const edited=await api('/dictionary-items/'+item.id,{version:item.version,name:'修订后可删除单位'},200,'PATCH');
 const preview=await api('/dictionary-deletion/unit/'+item.id);
 assert.equal(preview.deletable,true);assert.deepEqual(preview.references,[]);
 await api('/dictionary-deletion/unit/'+item.id,{version:item.version},409,'DELETE');
 await api('/dictionary-deletion/unit/'+item.id,{version:edited.version},200,'DELETE');
 assert.equal(one('SELECT id FROM dictionary_items WHERE id=?',item.id),undefined);
 assert.equal(one('SELECT COUNT(*) n FROM dictionary_item_versions WHERE item_id=?',item.id).n,0);
 const deletion=one("SELECT before_json FROM audit_events WHERE entity_id=? AND action='delete'",item.id);
 assert.equal(JSON.parse(deletion.before_json).archived_versions.length,2,'deleted configuration versions remain in the audit trail');
 await api('/dictionary-deletion/unit/'+item.id,undefined,404);
 const voltage=(await api('/dictionary-workspace')).items.find(x=>x.type_id==='voltage'&&x.name==='35kV');
 const used=await api('/dictionary-deletion/voltage/'+voltage.id);assert.equal(used.deletable,true);assert.equal(used.deletion_kind,'logical');assert.equal(used.references.find(x=>x.domain==='线路台账').count,1);
 const removedVoltage=await api('/dictionary-deletion/voltage/'+voltage.id,{version:voltage.version},200,'DELETE');assert.equal(removedVoltage.deletion_kind,'logical');
 assert.ok(one('SELECT id FROM voltage_levels WHERE id=?',voltage.id),'linked voltage row remains for historical joins');
 assert.ok(!(await api('/voltage-levels')).some(x=>x.id===voltage.id));
 await api('/voltage-levels/'+voltage.id,undefined,404);await api('/voltage-levels/'+voltage.id,{version:voltage.version+1,name:'绕过删除恢复'},404,'PATCH');
 assert.ok((await api('/lines')).some(x=>x.voltage_level_id===voltage.id));
 const unit=(await api('/dictionary-workspace')).items.find(x=>x.name==='修改后的单位');
 const configured=await api('/dictionary-deletion/unit/'+unit.id);assert.equal(configured.deletion_kind,'logical');assert.equal(configured.references.find(x=>x.domain==='操作单位定义').count,1);
 await api('/dictionary-deletion/unit/'+unit.id,{version:unit.version},200,'DELETE');
 assert.ok(!(await api('/dictionary-items')).some(x=>x.id===unit.id));
 await api('/dictionary-items/'+unit.id,{version:unit.version+1,name:'不能修改已删除词条'},404,'PATCH');
 await api('/dictionary-status/unit',{status:'active',rows:[{id:unit.id,version:unit.version+1}]},422);
 const historicalUnit=await api('/dictionary-items',{type_id:'unit',name:'仅被历史配置引用'},201);
 let historicalOp=await api('/dictionary-items',{type_id:'operation',operation_profile:{location_kinds:['tower'],default_location_kind:'tower',default_target_object:'',entry_hint:''},work_target_type:'line',name:'历史配置核查操作',default_unit_id:historicalUnit.id},201);
 await api('/dictionary-items/'+historicalOp.id,{version:historicalOp.version,default_unit_id:(await api('/dictionary-workspace')).items.find(x=>x.type_id==='unit'&&x.status==='active'&&x.id!==historicalUnit.id).id},200,'PATCH');
 const historical=await api('/dictionary-deletion/unit/'+historicalUnit.id);
 assert.equal(historical.deletion_kind,'logical');assert.ok(historical.references.some(x=>x.domain==='操作类型历史版本'));
 assert.ok(!historical.references.some(x=>x.domain==='操作单位定义'));
 await api('/dictionary-deletion/unit/'+historicalUnit.id,{version:historicalUnit.version},200,'DELETE');
 const source=await api('/dictionary-items',{type_id:'source',name:'草稿占用来源'},201);
 await api('/demand-batches/drafts',{sources:[{type_id:source.id}],rows:[]},201);
 const drafted=await api('/dictionary-deletion/source/'+source.id);assert.equal(drafted.deletion_kind,'logical');assert.ok(drafted.references.some(x=>x.domain==='需求草稿及提交批次'));
 await api('/dictionary-deletion/source/'+source.id,{version:source.version},200,'DELETE');
 const racing=await api('/dictionary-items',{type_id:'source',name:'预览后新增引用来源'},201);
 assert.equal((await api('/dictionary-deletion/source/'+racing.id)).deletion_kind,'physical');
 await api('/demand-batches/drafts',{sources:[{type_id:racing.id}],rows:[]},201);
 assert.equal((await api('/dictionary-deletion/source/'+racing.id,{version:racing.version},200,'DELETE')).deletion_kind,'logical');
 assert.ok(one('SELECT id FROM dictionary_items WHERE id=?',racing.id),'newly referenced record must not be physically removed');
 const builtin=(await api('/dictionary-workspace')).items.find(x=>x.type_id==='voltage'&&x.name==='1000kV');
 assert.equal((await api('/dictionary-deletion/voltage/'+builtin.id,{version:builtin.version},200,'DELETE')).deletion_kind,'physical');
 assert.equal(one('SELECT id FROM voltage_levels WHERE id=?',builtin.id),undefined);
 const archived=(await api('/dictionary-workspace')).deleted_items;
 assert.ok(archived.some(x=>x.id===unit.id&&x.status==='deleted'&&x.deletion_kind==='logical'));
 assert.ok(archived.some(x=>x.id===builtin.id&&x.builtin&&x.deletion_kind==='physical'));
 const remaining=(await api('/dictionary-workspace')).items.filter(x=>x.type_id==='unit').reverse().map(x=>({id:x.id,version:x.version}));
 await api('/dictionary-order/unit',{rows:remaining});
});
test('deleting built-in entries survives server restart and never restores hidden defaults',async()=>{
 const view=await api('/dictionary-workspace'),unit=view.items.find(x=>x.type_id==='unit'&&x.name==='套');
 const operation=view.items.find(x=>x.id==='builtin-operation-INSULATOR_CLEAN');
 assert.equal((await api('/dictionary-deletion/operation/'+operation.id,{version:operation.version},200,'DELETE')).deletion_kind,'physical');
 assert.equal((await api('/dictionary-deletion/unit/'+unit.id,{version:unit.version},200,'DELETE')).deletion_kind,'logical');
 execFileSync(process.execPath,['--input-type=module','-e',"await import('./server/main.mjs');"],{env:{...process.env,DATA_DIR:root,SD_DISABLE_LISTEN:'1'}});
 const reopened=await api('/dictionary-workspace');
 assert.ok(!reopened.items.some(x=>x.id===operation.id||x.id===unit.id||x.id==='builtin-voltage-AC1000'));
 assert.equal(one('SELECT id FROM operations WHERE id=?',operation.id),undefined);
 assert.equal(one('SELECT status FROM dictionary_items WHERE id=?',unit.id).status,'inactive');
 const again=await api('/dictionary-items',{type_id:'unit',name:'套'},201);assert.notEqual(again.id,unit.id);
 execFileSync(process.execPath,['--input-type=module','-e',"await import('./server/main.mjs');"],{env:{...process.env,DATA_DIR:root,SD_DISABLE_LISTEN:'1'}});
 assert.equal((await api('/dictionary-workspace')).items.filter(x=>x.type_id==='unit'&&x.name==='套').length,1);
});
